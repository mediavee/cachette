OUTCOMES = ("FROM-CACHE", "EXECUTED", "UP-TO-DATE", "NO-SOURCE", "SKIPPED", "FAILED")
TASK_LINE = re.compile(r"^> Task (\S+)(?: (FROM-CACHE|UP-TO-DATE|NO-SOURCE|SKIPPED|FAILED))?\s*$")
CACHE_WARNING = re.compile(r"remote build cache was disabled|Could not (?:load|store) entry", re.I)
TRACKED_METRICS = ("cachette_entries", "cachette_size_bytes", "cachette_hits_total",
                   "cachette_misses_total", "cachette_read_bytes_total",
                   "cachette_written_bytes_total", "cachette_puts_dropped_total")
# Flags whose value names the machine or the project: the report's replay line shows a placeholder.
# Task names of Gradle's core plugins and of the common plugins of a CI build. A task name is a
# fingerprint of the project, so any other name is replaced by a number in the report.
STANDARD_TASKS = frozenset("""
    assemble build buildDependents buildNeeded check classes clean components dependencies help init
    projects properties tasks testClasses wrapper
    compileJava compileTestJava processResources processTestResources jar javadoc javadocJar sourcesJar
    test testJar
    checkstyleMain checkstyleTest
    jacocoTestReport jacocoTestCoverageVerification
    publish publishToMavenLocal generatePomFileForMavenPublication generateMetadataFileForMavenPublication
    distTar distZip installDist startScripts assembleDist
    shadowJar shadowDistTar shadowDistZip installShadowDist startShadowScripts
    jmh jmhJar jmhClasses compileJmhJava processJmhResources jmhCompileGeneratedClasses jmhRunBytecodeGenerator
""".split())
REPLAY_PLACEHOLDERS = {"--project": "<project>", "--url": "<url>",
                       "--server-load-command": "<command printing the server's /proc/loadavg>",
                       "--work-dir": "<work-dir>", "--results": "<results>"}
INIT_SCRIPT = """\
// Generated by bench/gradle.py. The local cache is always off; the remote one comes from the
// environment, so that no secret is written to a file or to the command line.
gradle.settingsEvaluated { settings ->
    settings.buildCache {
        local { enabled = false }
        def endpoint = System.getenv('BENCH_CACHE_URL')
        if (endpoint) {
            remote(HttpBuildCache) {
                url = endpoint
                allowInsecureProtocol = endpoint.startsWith('http://')
                enabled = true
                push = Boolean.parseBoolean(System.getenv('BENCH_CACHE_PUSH'))
                credentials {
                    username = 'gradle'
                    password = System.getenv('BENCH_CACHE_TOKEN')
                }
            }
        } else if (remote != null) {
            remote.enabled = false
        }
    }
}
"""


class Refused(RuntimeError):
    """The run must not start or go on: the setup is not what the measurement assumes."""


def parse_outcomes(text):
    """Task path -> outcome, from the `> Task :path [OUTCOME]` lines of a plain-console build."""
    outcomes = {}
    for line in text.splitlines():
        match = TASK_LINE.match(line)
        if match:
            outcomes[match[1]] = match[2] or "EXECUTED"
    return outcomes


def tally(outcomes):
    counts = collections.Counter(outcomes.values())
    return {name: counts.get(name, 0) for name in OUTCOMES}


def hit_rate(outcomes):
    """FROM-CACHE over the tasks that ran or came from the cache; None when none did."""
    counts = tally(outcomes)
    denominator = counts["FROM-CACHE"] + counts["EXECUTED"]
    return counts["FROM-CACHE"] / denominator if denominator else None


def percentile(values, fraction):
    """Nearest-rank percentile."""
    ordered = sorted(values)
    return ordered[max(math.ceil(fraction * len(ordered)), 1) - 1]


def spread(values):
    return {"n": len(values), "median": statistics.median(values), "min": min(values),
            "max": max(values), "stdev": statistics.stdev(values) if len(values) > 1 else 0.0}


def parse_metrics(text):
    """Prometheus text exposition -> {"name{labels}": value}."""
    samples = {}
    for line in text.splitlines():
        if line and not line.startswith("#"):
            name, _, value = line.rpartition(" ")
            samples[name] = float(value)
    return samples


def metric_total(samples, name):
    """The sum over every label set of one metric, or None when the server does not expose it."""
    values = [v for key, v in samples.items() if key == name or key.startswith(name + "{")]
    return sum(values) if values else None


def tracked(samples):
    return {name: metric_total(samples, name) for name in TRACKED_METRICS}


def require_empty(samples):
    entries = metric_total(samples, "cachette_entries")
    if entries is None:
        raise Refused("Refusing: /metrics has no cachette_entries, so the server cannot be shown empty")
    if entries != 0:
        raise Refused(f"Refusing: the server holds {entries:g} entries; the fill needs an empty server")


def connect(url, timeout=30):
    parts = urlsplit(url)
    factory = http.client.HTTPSConnection if parts.scheme == "https" else http.client.HTTPConnection
    return factory(parts.hostname, parts.port, timeout=timeout)


def get(connection, path, headers=None):
    connection.request("GET", path, headers=headers or {})
    response = connection.getresponse()
    body = response.read()
    if response.status != 200:
        raise Refused(f"Refusing: GET {path} answered {response.status}")
    return body.decode()


def read_metrics(url, token=None):
    connection = connect(url)
    try:
        headers = {"Authorization": f"Bearer {token}"} if token else {}
        return get(connection, "/metrics", headers)
    finally:
        connection.close()


def round_trip(url, count=300):
    """`GET /healthz` on one kept-alive connection: the median and p99 of its round trip, in ms."""
    connection = connect(url)
    try:
        get(connection, "/healthz")
        times = []
        for _ in range(count):
            start = time.perf_counter()
            get(connection, "/healthz")
            times.append((time.perf_counter() - start) * 1000)
    finally:
        connection.close()
    return {"requests": count, "median_ms": statistics.median(times),
            "p99_ms": percentile(times, 0.99), "min_ms": min(times), "max_ms": max(times)}


def server_load(command):
    """One-minute load from a command that prints the server's `/proc/loadavg`; None without one."""
    if not command:
        return None
    output = subprocess.run(shlex.split(command), capture_output=True, text=True, timeout=60, check=True).stdout
    return float(output.split()[0])


def wait_for_quiet(read_loads, max_client, max_server, budget, *, sleep=time.sleep, interval=30):
    """Wait until both loads are under their limits. Returns (quiet, seconds waited)."""
    waited = 0
    while True:
        client, server = read_loads()
        if client <= max_client and (server is None or server <= max_server):
            return True, waited
        if waited >= budget:
            return False, waited
        sleep(interval)
        waited += interval


def alternating(repetition):
    """Odd repetitions measure the baseline first, even ones the hit first."""
    return ("baseline", "hit") if repetition % 2 else ("hit", "baseline")


def build_command(gradle, init_script, tasks, extra):
    return [str(gradle), "--no-daemon", "--console=plain", "--build-cache", "-I", str(init_script),
            *extra, *tasks]


def build_env(base, home, url=None, token=None, push=False):
    env = dict(base, GRADLE_USER_HOME=str(home))
    for name in ("BENCH_CACHE_URL", "BENCH_CACHE_TOKEN", "BENCH_CACHE_PUSH"):
        env.pop(name, None)
    if url:
        env.update(BENCH_CACHE_URL=url.rstrip("/") + "/", BENCH_CACHE_TOKEN=token,
                   BENCH_CACHE_PUSH="true" if push else "false")
    return env


def fresh_copy(project, destination, excluded):
    shutil.copytree(project, destination, symlinks=True, ignore=shutil.ignore_patterns(*excluded))


def project_of(task):
    return task.rpartition(":")[0] or ":"


def run_build(kind, project, work, home, init_script, tasks, extra, excluded, url, token, push, timeout):
    """One clean build of a fresh copy, in its own directory. Returns the build's record and log."""
    workspace = work / kind / "workspace"
    fresh_copy(project, workspace, excluded)
    gradle = workspace / "gradlew" if (workspace / "gradlew").exists() else "gradle"
    env = build_env(os.environ, home, url, token, push)
    start = time.monotonic()
    done = subprocess.run(build_command(gradle, init_script, tasks, extra), cwd=workspace, env=env,
                          capture_output=True, text=True, timeout=timeout)
    wall = time.monotonic() - start
    log = done.stdout + done.stderr
    shutil.rmtree(work / kind)
    outcomes = parse_outcomes(log)
    return {"kind": kind, "exit": done.returncode, "wall_seconds": wall, "outcomes": outcomes,
            "counts": tally(outcomes), "hit_rate": hit_rate(outcomes),
            "cache_warnings": sum(1 for line in log.splitlines() if CACHE_WARNING.search(line))}, log


class Scrubber:
    """Replaces what identifies the project and the machines, in this process's memory only."""

    def __init__(self, project, extra_names=(), url=None):
        given, project = Path(project).absolute(), Path(project).resolve()
        names = {project.name: "<project>", str(project): "<project-dir>", str(given): "<project-dir>",
                 str(Path.home()): "<home>",
                 getpass.getuser(): "<user>", socket.gethostname(): "<client>",
                 socket.gethostname().split(".")[0]: "<client>"}
        if url:
            names[urlsplit(url).hostname] = "<server>"
        names.update({name: "<redacted>" for name in extra_names})
        self.replacements = sorted((k for k in names if k), key=len, reverse=True)
        self.names = names

    def text(self, value):
        for name in self.replacements:
            value = re.sub(re.escape(name), self.names[name], value, flags=re.I)
        return value

    def forbidden(self):
        return self.replacements


def scrub_all(value, scrubber):
    """The value with every string in it scrubbed; dict keys are kept."""
    if isinstance(value, str):
        return scrubber.text(value)
    if isinstance(value, dict):
        return {key: scrub_all(item, scrubber) for key, item in value.items()}
    if isinstance(value, list):
        return [scrub_all(item, scrubber) for item in value]
    return value


def neutral_names(builds):
    """Replaces every task name outside STANDARD_TASKS by `task-NN`, in `module:task` outcome keys.

    Numbers follow first appearance over the builds in order, each build read in sorted key order,
    and one name keeps one number across the whole report.
    """
    numbers = {}
    for build in builds:
        renamed = {}
        for key, outcome in sorted(build["outcomes"].items()):
            module, _, name = key.partition(":")
            if name not in STANDARD_TASKS:
                name = numbers.setdefault(name, f"task-{len(numbers) + 1:02d}")
            renamed[f"{module}:{name}"] = outcome
        build["outcomes"] = dict(sorted(renamed.items()))


def anonymize(tasks):
    """Maps every project path to `module-NN` (sorted, so stable)."""
    projects = sorted({project_of(task) for task in tasks} - {":"})
    labels = {project: f"module-{number:02d}" for number, project in enumerate(projects, 1)}
    labels[":"] = "root"

    def rename(task):
        return f"{labels[project_of(task)]}:{task.rpartition(':')[2]}"
    return rename, labels


def assert_clean(text, scrubber, module_paths=()):
    """The last line of defence: the report names neither the project, nor a machine, nor a person."""
    lowered = re.sub(r"<(?:project|project-dir|home|user|client|server|redacted)>", "", text.lower())
    for name in [*scrubber.forbidden(), *(p.strip(":") for p in module_paths if len(p.strip(":")) > 3)]:
        if name.lower() in lowered:
            raise Refused("Refusing to write a report that still contains an identifying name")


def replay_command(argv):
    """The command line of this run with the paths, the URL and the host command replaced."""
    shown, skip = [], False
    for arg in argv:
        flag, equals, _ = arg.partition("=")
        if skip:
            skip = False
        elif flag in REPLAY_PLACEHOLDERS:
            shown.append(f"{flag}={shlex.quote(REPLAY_PLACEHOLDERS[flag])}" if equals else flag)
            skip = not equals
            if not equals:
                shown.append(shlex.quote(REPLAY_PLACEHOLDERS[flag]))
        else:
            shown.append(shlex.quote(arg))
    return "BENCH_WRITE_TOKEN=… BENCH_READ_TOKEN=… python3 -B bench/gradle.py " + " ".join(shown)


def report_identity(stamp):
    label = machine_label()
    return label, f"{stamp}-gradle-{label}.md"


def summarize(builds):
    """Baseline against hit, over the repetitions that measured both."""
    by_rep = collections.defaultdict(dict)
    for build in builds:
        if build["kind"] in ("baseline", "hit"):
            by_rep[build["repetition"]][build["kind"]] = build
    pairs = [(rep, got["baseline"], got["hit"]) for rep, got in sorted(by_rep.items())
             if "baseline" in got and "hit" in got]
    if not pairs:
        return None
    baseline = [b["wall_seconds"] for _, b, _ in pairs]
    hit = [h["wall_seconds"] for _, _, h in pairs]
    rates = [h["hit_rate"] for _, _, h in pairs if h["hit_rate"] is not None]
    return {"repetitions": len(pairs), "baseline": spread(baseline), "hit": spread(hit),
            "saved_seconds": statistics.median(baseline) - statistics.median(hit),
            "saved_percent": 100 * (1 - statistics.median(hit) / statistics.median(baseline)),
            "hit_rate": spread(rates) if rates else None,
            "pairs": [{"repetition": rep, "baseline_seconds": b["wall_seconds"], "hit_seconds": h["wall_seconds"],
                       "saved_seconds": b["wall_seconds"] - h["wall_seconds"], "hit_rate": h["hit_rate"]}
                      for rep, b, h in pairs]}


def raw_data(report_text):
    """The raw data block of a report written by `render`."""
    return json.loads(report_text.split("```json\n")[1].split("\n```")[0])


def delta(build, name):
    return build["metrics_after"][name] - build["metrics_before"][name]


def figures(data):
    """The numbers the README quotes, recomputed from a report's raw data.

    A lookup is a request that reached the cache: a Gradle task that is cacheable and not
    up to date asks the server once, so the server's hits plus misses count the cacheable tasks.
    """
    builds = {kind: [b for b in data["builds"] if b["kind"] == kind] for kind in ("fill", "baseline", "hit")}
    hits = builds["hit"]
    summary = summarize(data["builds"])
    rtt = data["round_trip"]
    loads = [b["client_load_before"][0] for b in data["builds"]]
    server_loads = [b["server_load_before"] for b in data["builds"] if b["server_load_before"] is not None]
    lookups = [delta(b, "cachette_hits_total") + delta(b, "cachette_misses_total") for b in hits]
    from_cache = [delta(b, "cachette_hits_total") for b in hits]
    return {
        "projects_with_tasks": len({task.partition(":")[0] for task in hits[0]["outcomes"]}),
        "tasks_per_build": statistics.median(len(b["outcomes"]) for b in hits),
        "from_cache_per_hit_build": statistics.median(b["counts"]["FROM-CACHE"] for b in hits),
        "hit_rate_ran_or_cached": summary["hit_rate"],
        "lookups_per_hit_build": statistics.median(lookups),
        "server_hits_per_hit_build": statistics.median(from_cache),
        "hit_rate_of_lookups": statistics.median(h / n for h, n in zip(from_cache, lookups)),
        "entries_stored_by_fill": delta(builds["fill"][0], "cachette_entries"),
        "bytes_stored_by_fill": delta(builds["fill"][0], "cachette_written_bytes_total"),
        "bytes_read_per_hit_build": statistics.median(delta(b, "cachette_read_bytes_total") for b in hits),
        "baseline_seconds": summary["baseline"], "hit_seconds": summary["hit"],
        "saved_seconds": summary["saved_seconds"], "saved_percent": summary["saved_percent"],
        "paired_saved_seconds": [pair["saved_seconds"] for pair in summary["pairs"]],
        "round_trip_ms": {name: {k: rtt[name][k] for k in ("median_ms", "p99_ms")} for name in ("before", "after")},
        "client_load_before_builds": [min(loads), max(loads)],
        "server_load_before_builds": [min(server_loads), max(server_loads)] if server_loads else None,
        "builds": {"baseline": len(builds["baseline"]), "hit": len(hits)},
    }


def minutes(seconds):
    return f"{seconds:.1f} s"


def render(path, data, scrubber):
    """Markdown report with the raw data. Task names are anonymized and the text is checked."""
    tasks = {task for build in data["builds"] for task in build["outcomes"]}
    rename, labels = anonymize(tasks)
    data = json.loads(json.dumps(data, default=str))
    for build in data["builds"]:
        build["outcomes"] = {rename(task): outcome for task, outcome in build["outcomes"].items()}
    neutral_names(data["builds"])
    data["meta"] = scrub_all(data["meta"], scrubber)
    # The prose below is fixed text; what can name something is in the data, which is checked.
    assert_clean(json.dumps(data), scrubber, [p for p in labels if p != ":"])
    summary = summarize(data["builds"])
    data["summary"] = summary
    meta = data["meta"]
    lines = [f"# Gradle build over a network — {meta['utc']} — {meta['host']}", "",
             "Generated by bench/gradle.py. Raw data is embedded below; module and machine names are replaced by labels, and so are all task names outside Gradle's standard ones.", "",
             "## Setup", "",
             f"- Tasks: `{meta['tasks']}`" + (f", extra Gradle arguments: `{meta['gradle_args']}`" if meta["gradle_args"] else ""),
             f"- Gradle: {meta['versions']['gradle']}; JVM: {meta['versions']['jvm']}; server: {meta['versions']['server']}",
             f"- Gradle daemon: {meta['daemon']}",
             f"- Gradle's local cache: disabled by an init script in every build. Dependencies and the Gradle distribution "
             f"come from one shared Gradle user home, filled by an unrecorded warm-up build.",
             f"- Each build is a clean build of a fresh copy of the project, in its own directory.",
             f"- Order within a repetition alternates: odd repetitions run baseline then hit, even ones hit then baseline.",
             f"- Modules with a task in the builds: {len({project_of(task) for task in tasks})}.",
             f"- Load limits to start a repetition: client {meta['max_client_load']}, server "
             f"{meta['max_server_load'] if meta['max_server_load'] is not None else 'not measured'}; waited {meta['waited_seconds']} s of "
             f"{meta['max_wait_seconds']} s. Repetitions asked: {meta['repetitions']}; completed: {meta['completed']}.",
             f"- Stopped early: {meta['stopped'] or 'no'}.", ""]
    if summary:
        base, hit = summary["baseline"], summary["hit"]
        lines += ["## Result", "",
                  f"| | median | min | max | stdev |", "|---|---:|---:|---:|---:|",
                  f"| baseline | {minutes(base['median'])} | {minutes(base['min'])} | {minutes(base['max'])} | {minutes(base['stdev'])} |",
                  f"| hit | {minutes(hit['median'])} | {minutes(hit['min'])} | {minutes(hit['max'])} | {minutes(hit['stdev'])} |", "",
                  f"Time saved by the cache (median baseline minus median hit): **{minutes(summary['saved_seconds'])}** "
                  f"({summary['saved_percent']:.1f} %), over {summary['repetitions']} repetitions.", ""]
        if summary["hit_rate"]:
            rate = summary["hit_rate"]
            lines += [f"Hit rate (`FROM-CACHE` over the tasks that ran or came from the cache, hit builds): "
                      f"median {100 * rate['median']:.1f} %, min {100 * rate['min']:.1f} %, max {100 * rate['max']:.1f} %.", ""]
        lines += ["| Repetition | Order | Baseline | Hit | Saved | Hit rate | Client load before (baseline / hit) |",
                  "|---:|---|---:|---:|---:|---:|---|"]
        by_key = {(b["repetition"], b["kind"]): b for b in data["builds"] if "repetition" in b}
        for pair in summary["pairs"]:
            rep = pair["repetition"]
            order = " → ".join(alternating(rep))
            loads = " / ".join(f"{by_key[(rep, kind)]['client_load_before'][0]:.1f}" for kind in ("baseline", "hit"))
            rate = "—" if pair["hit_rate"] is None else f"{100 * pair['hit_rate']:.1f} %"
            lines.append(f"| {rep} | {order} | {minutes(pair['baseline_seconds'])} | {minutes(pair['hit_seconds'])} | "
                         f"{minutes(pair['saved_seconds'])} | {rate} | {loads} |")
        lines.append("")
    else:
        lines += ["## Result", "", "No repetition measured both a baseline and a hit.", ""]
    rtt = data["round_trip"]
    lines += ["## Round trip to the server", "",
              "`GET /healthz` on one kept-alive connection, before the first build and after the last.", "",
              "| | requests | median | p99 | min | max |", "|---|---:|---:|---:|---:|---:|"]
    for name in ("before", "after"):
        if rtt.get(name):
            r = rtt[name]
            lines.append(f"| {name} | {r['requests']} | {r['median_ms']:.2f} ms | {r['p99_ms']:.2f} ms | "
                         f"{r['min_ms']:.2f} ms | {r['max_ms']:.2f} ms |")
    lines += ["", "## Builds", "",
              "| Build | Exit | Wall | FROM-CACHE | Executed | Up-to-date | No-source | Cache warnings |",
              "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for build in data["builds"]:
        c = build["counts"]
        name = build["kind"] + (f" {build['repetition']}" if "repetition" in build else "")
        lines.append(f"| {name} | {build['exit']} | {minutes(build['wall_seconds'])} | {c['FROM-CACHE']} | "
                     f"{c['EXECUTED']} | {c['UP-TO-DATE']} | {c['NO-SOURCE']} | {build['cache_warnings']} |")
    lines += ["", "## What this run does not show", "",
              "One client, one server, one project. The machines were shared, so loads are recorded per build rather "
              "than controlled. A single fill build populates the cache once; hit builds do not push.", "",
              "## Replay", "", "```sh", meta["replay"], "```", "",
              "<details><summary>Raw data</summary>", "", "```json", json.dumps(data, indent=2), "```", "", "</details>", ""]
    path.write_text("\n".join(lines))


def versions(gradle, workspace, env, timeout):
    text = subprocess.run([str(gradle), "--version", "--console=plain"], cwd=workspace, env=env,
                          capture_output=True, text=True, timeout=timeout).stdout
    found = {}
    for line in text.splitlines():
        for key, label in (("gradle", "Gradle "), ("jvm", "Launcher JVM:"), ("jvm", "JVM:")):
            if line.startswith(label) and key not in found:
                found[key] = line[len(label):].strip() if key == "jvm" else line.strip()
    return found


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--summary", type=Path, metavar="REPORT",
                        help="print the figures a README quotes from a report, and exit")
    parser.add_argument("--project", type=Path, help="the Gradle project directory")
    parser.add_argument("--url", help="the cache server's base URL, e.g. http://host:5071")
    parser.add_argument("--tasks", help='the Gradle tasks, one string, e.g. "build -x test"')
    parser.add_argument("--repetitions", type=int, default=5)
    parser.add_argument("--gradle-arg", action="append", default=[], help="an extra Gradle argument for every build")
    parser.add_argument("--exclude", action="append", default=["build", ".gradle", ".kotlin"],
                        help="a name left out of each fresh copy (repeatable)")
    parser.add_argument("--redact", action="append", default=[], help="an extra name to replace in the report")
    parser.add_argument("--server-version", default="unknown", help="free text recorded in the report")
    parser.add_argument("--server-load-command", help="prints the server host's load, e.g. 'ssh host cat /proc/loadavg'")
    parser.add_argument("--max-client-load", type=float, default=16)
    parser.add_argument("--max-server-load", type=float, default=8)
    parser.add_argument("--max-wait", type=int, default=7200, help="seconds to wait for quiet loads, in total")
    parser.add_argument("--build-timeout", type=int, default=3600)
    parser.add_argument("--work-dir", type=Path, default=Path(tempfile.gettempdir()))
    parser.add_argument("--results", type=Path, default=Path(__file__).resolve().parent / "results")
    args = parser.parse_args()
    if args.summary:
        print(json.dumps(figures(raw_data(args.summary.read_text())), indent=2))
        return
    if args.repetitions < 1 or not args.url or not args.project or not args.project.is_dir() \
            or not args.tasks or not shlex.split(args.tasks):
        parser.error("--project (an existing directory), --url, --tasks and repetitions >= 1 are required")
    tokens = {name: os.environ.get(name) for name in ("BENCH_WRITE_TOKEN", "BENCH_READ_TOKEN")}
    if not all(tokens.values()):
        parser.error("BENCH_WRITE_TOKEN and BENCH_READ_TOKEN must be set in the environment")
    metrics_token = os.environ.get("BENCH_METRICS_TOKEN")
    base = args.url.rstrip("/")
    tasks, extra = shlex.split(args.tasks), args.gradle_arg
    scrubber = Scrubber(args.project, args.redact, args.url)

    require_empty(parse_metrics(read_metrics(base, metrics_token)))
    work = Path(tempfile.mkdtemp(prefix="gradle-bench-", dir=args.work_dir))
    home, init_script = work / "gradle-home", work / "bench.init.gradle"
    init_script.write_text(INIT_SCRIPT)
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H%M%SZ")
    host, name = report_identity(stamp)
    data = {"meta": {"utc": stamp, "host": host, "tasks": args.tasks, "gradle_args": " ".join(extra),
                     "daemon": "none (--no-daemon) for every build, as on a fresh CI runner",
                     "max_client_load": args.max_client_load,
                     "max_server_load": args.max_server_load if args.server_load_command else None,
                     "max_wait_seconds": args.max_wait, "repetitions": args.repetitions, "completed": 0,
                     "waited_seconds": 0, "stopped": None, "versions": {"server": args.server_version},
                     "replay": replay_command(sys.argv[1:])},
            "builds": [], "round_trip": {}, "metrics": {}}
    failure = None

    def loads():
        return os.getloadavg(), server_load(args.server_load_command)

    def quiet():
        ok, waited = wait_for_quiet(lambda: (os.getloadavg()[0], server_load(args.server_load_command)),
                                    args.max_client_load, args.max_server_load, args.max_wait - data["meta"]["waited_seconds"])
        data["meta"]["waited_seconds"] += waited
        if not ok:
            data["meta"]["stopped"] = f"loads stayed above the limits for {data['meta']['waited_seconds']} s"
        return ok

    def measure(kind, url, token, push, repetition=None, keep=True):
        client, server = loads()
        before = parse_metrics(read_metrics(base, metrics_token))
        if kind == "fill":
            require_empty(before)
        record, log = run_build(kind, args.project, work, home, init_script, tasks, extra, args.exclude,
                                url, token, push, args.build_timeout)
        after = parse_metrics(read_metrics(base, metrics_token))
        record.update(client_load_before=client, server_load_before=server, client_load_after=os.getloadavg(),
                      server_load_after=server_load(args.server_load_command),
                      metrics_before=tracked(before), metrics_after=tracked(after))
        if repetition is not None:
            record["repetition"] = repetition
        if keep:
            data["builds"].append(record)
        print(f"{kind}{'' if repetition is None else f' {repetition}'}: exit {record['exit']}, "
              f"{record['wall_seconds']:.1f} s, hit rate {record['hit_rate']}", flush=True)
        if record["exit"]:
            raise Refused(f"the {kind} build failed (exit {record['exit']}):\n" + scrubber.text("\n".join(log.splitlines()[-40:])))
        return record

    try:
        data["round_trip"]["before"] = round_trip(base)
        data["metrics"]["before"] = read_metrics(base, metrics_token)
        if quiet():
            gradle = args.project / "gradlew" if (args.project / "gradlew").exists() else "gradle"
            data["meta"]["versions"].update(versions(gradle, args.project, build_env(os.environ, home), args.build_timeout))
            measure("warmup", None, None, False, keep=False)
            measure("fill", base, tokens["BENCH_WRITE_TOKEN"], True)
            for repetition in range(1, args.repetitions + 1):
                if not quiet():
                    break
                for kind in alternating(repetition):
                    if kind == "baseline":
                        measure("baseline", None, None, False, repetition)
                    else:
                        measure("hit", base, tokens["BENCH_READ_TOKEN"], False, repetition)
                data["meta"]["completed"] += 1
    except BaseException as exc:
        failure = f"{type(exc).__name__}: {exc}"
        data["meta"]["stopped"] = failure
        raise
    finally:
        try:
            data["round_trip"]["after"] = round_trip(base)
            data["metrics"]["after"] = read_metrics(base, metrics_token)
        except OSError:
            pass
        shutil.rmtree(work, ignore_errors=True)
        data["meta"]["client"] = f"{platform.system()} {platform.machine()}, {os.cpu_count()} threads"
        target = args.results / name if not failure else args.work_dir / f"failed-{name}"
        args.results.mkdir(parents=True, exist_ok=True)
        render(target, data, scrubber)
        print(target, flush=True)


if __name__ == "__main__":
    try:
        main()
    except Refused as exc:
        sys.exit(str(exc))
