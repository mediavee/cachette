#!/usr/bin/env python3
"""A real Gradle build against a build cache server, over a real network.

Python's standard library only. For each repetition every build is a clean build of a fresh copy of
the project, with Gradle's local cache disabled by an init script (the project is left untouched):

  baseline  no remote cache;
  fill      remote cache with push and the write token, once, against an empty server;
  hit       remote cache with the read token, from another directory.

Tokens come from the environment (BENCH_WRITE_TOKEN, BENCH_READ_TOKEN, optionally
BENCH_METRICS_TOKEN), never from the command line.
"""
